                $"上次抬手 #{releaseSerial}：{(lastReleaseWasDrag ? "判为拖动（未产生点击）" : "判为点击")}　" +
                $"位移 {lastPressMoveMM:F1} mm　阈值 {dragThresholdMM:F1} mm",
