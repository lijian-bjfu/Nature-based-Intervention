/// V1 首测（2026-08-06）发现四件事，均已在本版本修正。之所以逐条记下来，是因为
/// 其中几条从代码上看都"很有道理"，不写清楚就会被重新加回去：
///
///   (1) 终点判定里用"命中点与脚下的绝对高差"来判能不能去 —— **删除**
///       这是首测中"点什么都变成我想看""卡在河沟里进退维谷"的主因。
///       错在：你和一个远处的点之间的高差，跟能不能走过去毫无关系。
///       一道 20 米长的缓坡可以升高 5 米，一路都好走，但高差是 5 米。
