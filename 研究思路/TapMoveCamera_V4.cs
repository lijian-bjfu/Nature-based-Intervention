        // 站在不同的坡上点一点，把这个读数记下来，就是在给 maxWalkableSlope 找依据。
        debugLines.Add(new DebugLine(
            $"命中处坡度：{lastHitSlope:F1}°　(停留阈值 {maxWalkableSlope:F0}° / 路过阈值 {pathMaxSlope:F0}°)",
