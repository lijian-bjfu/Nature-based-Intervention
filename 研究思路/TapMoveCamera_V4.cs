    void Update()
    {
        // 【V2 新增】分辨率或朝向变了就重算换算系数。
        // 每帧比两个整数，开销可忽略；不做的话，横竖屏切换或分辨率缩放变更之后
        // 所有物理量都会静默偏掉——而那正是最难查的一类问题。
        if (Screen.width != lastScreenWidth || Screen.height != lastScreenHeight)
        {
            ResolveDpi();
            RecomputeDeviceDerivedValues();
        }

        // 帧率平滑，仅供调试框显示。
        if (Time.unscaledDeltaTime > 0.0001f)
        {
            float instant = 1f / Time.unscaledDeltaTime;
            smoothedFps = (smoothedFps <= 0f) ? instant : Mathf.Lerp(smoothedFps, instant, 0.1f);
        }

        HandleTapInput();

        // 诊断用：当前位置是否处在阻挡层（深水板）范围内。
        // 若显示"是"却仍能走进来，说明是路径采样没拦住；
        // 若显示"否"而人明明泡在水里，说明水板的水平覆盖没铺到这儿、或几块之间有缝。
        if (showDebugOverlay && hasGround)
        {
            blockedUnderfoot = IsBlockedAt(Flat(transform.position), currentGroundY);
        }

        UpdateTurning();

        // 【V3 新增】头部朝向的惯性追赶。必须排在 UpdateTurning 之后：
        // UpdateTurning 会改 bodyYaw、也会（移动时）把头部目标拉回正前，
        // 本函数把这些变化统一落到画面上。相机的旋转现在只在这一个地方施加，
        // 不再散落在各处——这也是为什么 UpdateTurning 里那个 ApplyCameraRotation
        // 被去掉了（见该处注释）。
        UpdateLookSmoothing();

        UpdateMovement();
        UpdateGroundHeight();

        // 【V4 新增】可及范围圆环。纯显示，排在最后，不影响任何上面的计算。
        UpdateReachIndicator();
    }


    // ========================================================================
    // 【V4 新增】可及范围指示
    //
    // 用 LineRenderer 而不是 Gizmos：Gizmos 只在 Scene 视图里看得见，而本轮要
    // 判断的是**在 Game 视图/真机上看着够不够得着**，那正是 Gizmos 不出现的地方。
    //
    // 用 LineRenderer 而不是 GL/OnRenderObject：URP 下 OnPostRender 一类的回调
    // 不可靠，LineRenderer 是普通渲染对象，管线怎么变都在。
    //
    // ⚠ 这个对象是运行时创建的，带 HideFlags.DontSave，不会污染场景文件。
    // ========================================================================

    private GameObject reachIndicatorGO;
    private LineRenderer reachRing;
    private Material reachRingMat;
    private const int ReachRingSegments = 64;

    /// <summary>
    /// 上次命中点当前离相机多远（水平距离，每帧更新）。
    ///
    /// ※ 与 lastHitDistance 的区别很要紧，不要混：
    ///     lastHitDistance —— 点击那一刻射线的长度，是个**快照**，人走过去之后就过期了
    ///     liveHitDistance —— 现在离那个点多远，是本轮真正要读的数
    ///   V3 的调试框只有前者，所以回答不了"到位之后离它多远"。
    /// </summary>
    private float liveHitDistance;
    private bool liveHitInReach;

    private void UpdateReachIndicator()
    {
        // 先算读数——它与画不画圆环无关，调试框那一组要用。
        if (hasLastHit)
        {
            liveHitDistance = (Flat(lastHitPoint) - Flat(transform.position)).magnitude;
            liveHitInReach = liveHitDistance <= reachRadius;
        }
        else
        {
            liveHitDistance = -1f;
            liveHitInReach = false;
        }

        bool wanted = showReachIndicator && showTouchDebug && Application.isPlaying;

        if (!wanted)
        {
            if (reachIndicatorGO != null) reachIndicatorGO.SetActive(false);
            return;
        }

        EnsureReachIndicator();
        reachIndicatorGO.SetActive(true);

        // 圆环挂在世界里、不挂在相机上：挂上去会跟着俯仰翻转，那就不是"地面上的
        // 一圈"了。这里每帧只更新位置，旋转恒为单位——圆环永远水平。
        float baseY = hasGround ? currentGroundY : (transform.position.y - eyeHeight);
        reachIndicatorGO.transform.position =
            new Vector3(transform.position.x, baseY + reachIndicatorHeight, transform.position.z);

        // 半径可能被随时改，所以每帧重建点。64 个点、一帧一次，开销可忽略。
        BuildRingPoints(reachRing, reachRadius);

        // 颜色随"上次命中点在不在圈内"变化。
        // 这一条是本组唯一的"信息"设计：有了它，测试时不必回头对数字，
        // 走到跟前看一眼圈是不是绿的就知道够不够得着。
        Color c = liveHitInReach
            ? new Color(0.4f, 1f, 0.5f, 0.85f)      // 够得着
            : new Color(1f, 0.85f, 0.35f, 0.55f);   // 还够不着
        reachRing.startColor = c;
        reachRing.endColor = c;
    }

    private void EnsureReachIndicator()
    {
        if (reachIndicatorGO != null) return;

        reachIndicatorGO = new GameObject("ReachIndicator (V4 Debug)");
        reachIndicatorGO.hideFlags = HideFlags.DontSave;

        reachRing = reachIndicatorGO.AddComponent<LineRenderer>();
        reachRing.useWorldSpace = false;
        reachRing.loop = true;
        reachRing.widthMultiplier = 0.02f;
        reachRing.numCapVertices = 0;
        reachRing.shadowCastingMode = UnityEngine.Rendering.ShadowCastingMode.Off;
        reachRing.receiveShadows = false;
        reachRing.alignment = LineAlignment.View;

        // Hidden/Internal-Colored 是 Unity 内置的无光照顶点色着色器，各管线都在。
        // 关掉深度测试是有意的：圆环要在密丛里也看得见，否则最需要它的场合恰好
        // 被叶子挡住。它是仪表不是场景内容，遮挡关系不必真实。
        Shader s = Shader.Find("Hidden/Internal-Colored");
        if (s == null) s = Shader.Find("Sprites/Default");

        reachRingMat = new Material(s);
        reachRingMat.hideFlags = HideFlags.HideAndDontSave;
        if (reachRingMat.HasProperty("_ZTest"))
            reachRingMat.SetInt("_ZTest", (int)UnityEngine.Rendering.CompareFunction.Always);
        if (reachRingMat.HasProperty("_ZWrite"))
            reachRingMat.SetInt("_ZWrite", 0);
        if (reachRingMat.HasProperty("_SrcBlend"))
            reachRingMat.SetInt("_SrcBlend", (int)UnityEngine.Rendering.BlendMode.SrcAlpha);
        if (reachRingMat.HasProperty("_DstBlend"))
            reachRingMat.SetInt("_DstBlend", (int)UnityEngine.Rendering.BlendMode.OneMinusSrcAlpha);
        if (reachRingMat.HasProperty("_Cull"))
            reachRingMat.SetInt("_Cull", (int)UnityEngine.Rendering.CullMode.Off);
        reachRingMat.renderQueue = 5000;

        reachRing.material = reachRingMat;
    }

    private void BuildRingPoints(LineRenderer lr, float radius)
    {
        if (lr.positionCount != ReachRingSegments)
            lr.positionCount = ReachRingSegments;

        for (int i = 0; i < ReachRingSegments; i++)
        {
            float a = (i / (float)ReachRingSegments) * Mathf.PI * 2f;
            lr.SetPosition(i, new Vector3(Mathf.Cos(a) * radius, 0f, Mathf.Sin(a) * radius));
        }
    }

    void OnDestroy()
    {
        if (reachIndicatorGO != null) Destroy(reachIndicatorGO);
        if (reachRingMat != null) Destroy(reachRingMat);
    }

