/// ════════════════════════════════════════════════════════════════════════════
/// 【首轮实测后的两处修订 —— 2026-08-10】
///
/// 边走边看与停下来上桌面测过一轮，暴露两个问题，都已修订。
///
/// ── 修订一：松手之后，视角不该立刻转走 ──
///
/// 报告：松手后回正立即开始，「像毫无目标的胡乱转头」。
///
/// 诊断不是快慢，是**语义被读反了**。「松手」在这套设计里出现三次：
///     点击松手       → 相机朝向那个地方
///     站定拖动松手   → 相机停在那儿，且那儿成为新的正前方
///     移动中拖动松手 → 相机立刻转走            ← 反了
/// 前两处说「这就是我要看的」，第三处说「我不看了」。而人环顾时松手，
/// 往往正是因为落点上有想多注视一下的东西。
///
/// 而指数逼近恰好是最坏的曲线：角速度 ∝ 剩余偏角，**偏得最多的那一刻最快**，
/// 那一刻正是刚松手想多看两眼的时候。所以调大 headReturnTime 无效。
///
/// 改为临界阻尼（初速为零，先慢后快再收尾），停留成为曲线起点的自然性质而非
/// 一个可被察觉的状态。新增 headReturnEaseIn（true = 新行为缓入，false = 旧行为，
/// 默认 true，false 那一支只为 A/B 对照保留）。手指按下时清零漂移速度状态，
/// 否则第二次之后停留会失效。
///
/// ※ 这是本项目**第三次**遇到同一件事（V1 身体转向、V3 头部转动、此处回正）。
///   三次抱怨措辞不同，三次病因都是曲线不对而非速度不对。已升为通则：
///   **听到「这个动作不像人做的」，先查曲线，别先动速度。**
///
/// ── 修订二：停下来是有滞后的，而且连点会越点越走 ──
///
/// 报告：想停 → 没立刻停 → 以为没点中 → 再点一次 → 又设了新目标 → 越点越停不下来。
/// 而且这把注意力从环境强行拽回了操作。研究者本人（知道规则）也踩了进去——
/// 因为触发条件不是「不知道规则」，是「注意力不在操作上」，恰恰是实验想要的状态。
/// 所以「事前让被试练习」解决不了。
///
/// 病灶不在设计，在 walkKeepDistance 的**取值**。那个「不移动、只转身」的纯停
/// 分支一直都在（与走过去并列，不是新语义），但门槛 1.0 + 0.2 远小于平视时画面里
/// 最近的地面（本项目 FOV 51.28、眼高 1.7 → 3.54 m），所以永远够不着。
///
/// 改为按几何取值：walkKeepDistance ≥ eyeHeight / tan(垂直FOV / 2)，默认 4.0。
/// 达标后点画面下缘直接进纯停分支，**连点变成幂等操作**——这条比「停得快」更要紧，
/// 它让「忘了规则」不再有惩罚。实测确认：只剩约 0.21 m 的余速滑停（那是刻意保留的
/// 身体存在感），主观评价自然。
///
/// 新增调试读数：近场几何、残余量、是否纯停；低于几何门槛时**不受分组开关控制地**
/// 红字告警——这两个数一个在 Inspector 一个由相机 FOV 隐含决定，不匹配时的表现
/// 和「参数没调好」一模一样。
///
