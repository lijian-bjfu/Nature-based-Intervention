    /// <summary>
    /// 【V3 后半段 · 坡地实测后重写】当下能指到的最近的地面有多远（水平距离）。
    ///
    /// 从画面下缘中心打一条射线，取命中点与自己的水平距离。被试想停时点画面下缘，
    /// 那一击最近也只能落在这么远的地方，所以这个数决定了「停」此刻有多利落：
    ///
    ///     点画面下缘之后还要走多远 = 本函数 − walkKeepDistance
    ///
    /// 【为什么改成实测 —— 原写法是错的】
    /// 原写法是 eyeHeight / tan(FOV/2)，一个只在**平地 + 平视**下成立的常数。
    /// 坡地实测里它在两张截图中都报了 3.54，而真值分别约 1.5（上坡）和 8 米以上
    /// （下坡）。俯仰角单独就足以让它失效：平地低头 30°，真值掉到约 1.28。
    /// 调试框里挂一个恒定为假的数，比没有这一行更糟——它会在将来某次排查里
    /// 把人带偏。
    ///
    /// 【只用于显示，绝不参与判定 —— 这一条是设计结论，不是实现偷懒】
    /// 用它当停止阈值（即「你能指到的最近处 = 这儿」）在设计上已被否决：
    /// 那样一来参照物就从「以我为中心的世界半径」变成了「画面下缘」，
    /// 而一条以画面边缘为参照的规则，和一个贴在屏幕底部的停止按钮没有区别——
    /// 后者还更诚实、更简单。研究者本人给出的正是这条反驳。
    ///
    /// 由此还得到一个更强的结论，记在这里免得将来重走：
    ///   上坡时地面迎面抬起（可指到约 1.5m），「点近处」的自然含义是**踩那儿**；
    ///   下坡时地面塌下去（可指到 8m 以上），「点近处」的含义才是**停**。
    ///   两者对 walkKeepDistance 的要求方向相反，因此
    ///   **任何单靠距离阈值同时解决二者的方案，必然是屏幕参照的。**
    ///   距离这条路到此为止；「停」若要做好，必须有独立的输入通道。
    /// </summary>
    private float NearestTappableGroundDistance()
    {
        if (cam == null) return 0f;

        // 画面下缘中心。取 y = 1 像素而不是 0，避免个别平台在边界像素上取不到射线。
        Ray ray = cam.ScreenPointToRay(new Vector3(Screen.width * 0.5f, 1f, 0f));

        if (Physics.Raycast(ray, out RaycastHit hit, tapRayDistance, tapRayMask))
        {
            Vector3 d = Flat(hit.point) - Flat(transform.position);
            return d.magnitude;
        }

        // 打不到（视线朝天、或超出射线距离）。返回一个大数，表示「此刻无法指到近处」，
        // 这样告警行会如实亮起——那正是下坡时的真实处境。
        return tapRayDistance;
    }


    /// <summary>
    /// 一帧的手指位移 → 累加到头部朝向的**目标值**上。
    ///
    /// 【V3 改】这个函数现在**不再直接改变画面**。它只更新意图；把意图变成画面
    /// 是 UpdateLookSmoothing() 的事。
    ///
    /// 这一句话就是 V3 的全部改动所在。V2 里手指位移直接落到 headYaw 上，画面因此
    /// 刚性地挂在手指上——手指能瞬间换向，画面就跟着瞬间换向，于是"像用手拨一个
    /// 物体"。人的头做不到瞬间换向，因为头有质量。中间这一层就是那个质量。
    ///
    /// ※ 灵敏度（度/厘米）的含义没有变：它仍然决定"划过 1 厘米，视角最终转多少度"。
    ///   惯性只影响这个转动**怎么发生**，不影响它**发生多少**。
    ///   所以调惯性不会让人觉得灵敏度变了——这正是选择"滞后加在角度上"的收益。
    /// </summary>
    private void ApplyLookDrag(Vector2 delta)
    {
        // 【V2 改】用 lookSensDegPerPx（由 lookSensitivityDegPerCm 按 DPI 折算而来），
        // 不再直接用一个以像素定义的灵敏度。见该参数注释。
        float yawInput = delta.x * lookSensDegPerPx;
        float pitchInput = -delta.y * lookSensDegPerPx;

        // 【V3 改】限位与阻尼施加在目标上。
        // 阻尼约束的是"意图能推到多远"，属于脖子的事，与惯性无关，两者互不干扰。
        headYawTarget = ApplyLimitedRotation(headYawTarget, yawInput, maxYawAngle);
        headPitchTarget = ApplyLimitedRotation(headPitchTarget, pitchInput, maxPitchAngle);

        // 这里**不**调用 ApplyCameraRotation()。见函数摘要。
    }


    /// <summary>
    /// 【V3 新增 · 本版本的核心】头部朝向的惯性追赶。每帧一次。
    ///
    /// 实际角度用缓入缓出去追目标角度。SmoothDamp 是一个临界阻尼的二阶系统：
    /// 起转有加速、收尾有减速、**不过冲**。不过冲这一条很要紧——过冲会让画面
    /// 越过手指指定的位置再荡回来，那是弹簧不是脖子。
    ///
    /// 【它为什么能压住"来回晃"，却不压住"快速划一下"】
    ///
    /// 因为它本质是个低通滤波器，按**频率**衰减而不是按幅度衰减：
    ///
    ///   - 手指快速划一下再停住：这是一个阶跃，主要成分在低频。系统会加速起来、
    ///     很快跑完、然后收住。**速度照样很快**，只是不再是死起死停。
    ///   - 手指快速左右晃：目标值在原点附近高频往复，系统的响应还没到位就被要求
    ///     反向了，于是幅度被自然压掉——这正是有质量的头会发生的事。
    ///
    /// 要保留的和要去掉的落在频率轴的两侧，所以一个机制就够，不需要判断"这次是
    /// 想快转还是在乱晃"。**不要在这里加任何形如"速度超过 X 就衰减"的启发式**：
    /// 那会造成同样的手势有时听话有时不听话，比现在的问题更难受，也更容易被被试
    /// 察觉成"这个系统有脾气"。
    /// </summary>
    private void UpdateLookSmoothing()
    {
        if (lookSmoothTime <= 0.0001f)
        {
            // 无惯性分支：目标即实际。**这一分支逐帧等价于 V2 的行为。**
            // 保留它不是为了兼容，是为了能在设备上直接做 A/B 对照——
            // 把 lookSmoothTime 在 0 和 0.12 之间来回切，感受差别比看任何读数都准。
            headYaw = headYawTarget;
            headPitch = headPitchTarget;
            headYawVelocity = 0f;
            headPitchVelocity = 0f;
        }
        else
        {
            // 用 Mathf.SmoothDamp 而不是 SmoothDampAngle：headYaw / headPitch 是
            // 被 clamp 在 ±maxYawAngle / ±maxPitchAngle 内的**相对偏角**，不存在
            // 359°→1° 的绕回问题。用角度版反而会在极限附近引入不必要的绕回判断。
            //（bodyYaw 是世界朝向，会绕回，所以那边用的是 SmoothDampAngle。）
            headYaw = Mathf.SmoothDamp(
                headYaw, headYawTarget, ref headYawVelocity,
                lookSmoothTime, lookMaxAngularSpeed, Time.deltaTime);

            headPitch = Mathf.SmoothDamp(
                headPitch, headPitchTarget, ref headPitchVelocity,
                lookSmoothTime, lookMaxAngularSpeed, Time.deltaTime);
        }

        ApplyCameraRotation();
    }


    /// <summary>
    /// 【V3 新增】把头部当前的偏角"折叠"进身体朝向，使 headYaw 归零而画面不动。
    ///
    /// V2 里这件事只有两行（bodyYaw = transform.eulerAngles.y; headYaw = 0;），
    /// 出现在三个地方。有了惯性之后它不再是两行，因为此刻可能还有一段没走完的
    /// 追赶——直接归零会把它截断，画面顿一下。所以抽成一个函数，三处共用。
    ///
    /// 【两种模式，差别只在"没走完的那一段怎么办"】
    ///
    /// preserveResidual = true（松手时用）
    ///   把余量换算到新的身体朝向下继续走完。
    ///   数学上：设折叠前实际偏角 a、目标偏角 b，余量 r = b - a。
    ///   折叠后 bodyYaw += a，实际偏角置 0，目标偏角置 r。
    ///   于是最终朝向 = (bodyYaw + a) + r = bodyYaw + b —— **与折叠前的目标一致**。
    ///   也就是说：吸收这个动作不吃掉任何一度旋转，手指划了多少最终就转多少。
    ///
    /// preserveResidual = false（点击转身时用）
    ///   连余量一起丢掉。因为点击是新的意图，它接管画面，旧的余量继续走只会
    ///   在身体转向上叠一层无来由的漂移。
    ///
    /// 两种模式下**画面在折叠那一帧都不动**（只是把同一个朝向换了个记法），
    /// 所以都不会产生跳变。
    /// </summary>
    private void FoldHeadYawIntoBody(bool preserveResidual)
    {
        float actual = headYaw;
        float residual = headYawTarget - actual;

        // 用 transform 的实际欧拉角而不是 bodyYaw + headYaw，与 V2 保持一致：
        // 这样即便有别处改过 transform.rotation，折叠也不会引入偏差。
        bodyYaw = transform.eulerAngles.y;
        headYaw = 0f;

        if (preserveResidual)
        {
            // 余量必然很小（临界阻尼系统的滞后量），clamp 只是防御性的。
            headYawTarget = Mathf.Clamp(residual, -maxYawAngle, maxYawAngle);
            // headYawVelocity 保持不变：让收尾的那一段继续按原来的势头走完，
            // 而不是重新起步。归零的话会看到"停一下再动一下"。
        }
        else
        {
            headYawTarget = 0f;
            headYawVelocity = 0f;
        }

        // 俯仰不参与折叠——身体朝向只有 yaw，pitch 无处可折。
        // V2 在这三处也都没动 headPitch，此处保持一致。
    }

    /// <summary>
    /// 接近转动极限时逐渐变黏，模拟脖子的生理限制。
    ///
    /// ※ 修正了旧版的一处：旧版按 |当前角度|/极限 算阻力，不看输入方向。结果是视角
    ///   已经偏到 65° 时，**往回拉和继续往外推一样费劲**。跟随蝴蝶这类"甩出去再
    ///   收回来"的动作，收回来那一半是黏的。现在只在"继续往外推"时施加阻力。
    /// </summary>
    private float ApplyLimitedRotation(float currentAngle, float inputDelta, float limit)
    {
        bool pushingOutward = Mathf.Sign(inputDelta) == Mathf.Sign(currentAngle) || Mathf.Approximately(currentAngle, 0f);

        float effectiveInput = inputDelta;

        if (pushingOutward)
        {
            float normalized = Mathf.Clamp01(Mathf.Abs(currentAngle) / Mathf.Max(0.01f, limit));
            float resistance = Mathf.Pow(normalized, lookResistancePower);
            effectiveInput = inputDelta * (1f - resistance);
        }

        return Mathf.Clamp(currentAngle + effectiveInput, -limit, limit);
    }

    private void ApplyCameraRotation()
    {
        transform.rotation = Quaternion.Euler(headPitch, bodyYaw + headYaw, 0f);
    }


