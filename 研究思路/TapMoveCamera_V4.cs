///   ⚠ V4 是新文件、新 GUID，挂上去之后 **Inspector 参数会全部回到代码默认值**，
///     换之前请先抄一份 V3 面板上的值（尤其 lookSmoothTime / headReturnTime /
///     walkKeepDistance / 三个层遮罩）。
///   ⚠ V3 与 V4 不能同时放在 Assets 里（同名文件不冲突，但两个脚本会同时跑）。
///
/// ----------------------------------------------------------------------------
/// 以下为 V3 原文，除标注 "【V4】" 处外未作改动。
/// ----------------------------------------------------------------------------
///
/// 【V3 是什么，不是什么 —— 2026-08-08】
///
/// V3 = V2 + 环顾（拖动）的惯性。**点击判定逻辑一行未动。**
/// ResolveTap / ClassifyHit / SampleWalkablePath / SampleGround / IsBlockedAt /
/// 移动与身体转向，全部与 V2 逐字相同。V1、V2 的所有注释原样保留，包括那些
/// "不要加回去"的告诫。
///
/// ────────────────────────────────────────────────────────────────────────────
/// 【本轮要解决的现象（研究者实测报告，2026-08-08）】
///
///   "手指头可以快速地左右晃动，场景就跟着左右晃动。这种感觉特别像是用手在
///    拨动一个物体在观察，而不像头部自然转动来观察环境。"
///
/// 【诊断：问题不在速度上，在换向上】
///
/// 第一反应会把这件事归因为"转太快了"，于是想到把灵敏度调小。这条路走不通，
/// 而且研究者自己已经把它的死结说清楚了：
///
///   被试想快速看右边时，本来就会猛地划一下手指——那**就是**"猛地转头"的意图。
///   如果手指速度控制不了旋转速度，那同样是反直觉的。
///
/// 但这个两难成立的前提是"问题出在速度上"。它不成立，理由是一条生理事实：
///
///   **人的头并不慢。**一次快速扫视式的转头可达每秒三四百度，比手指在屏幕上
///   划出来的角速度只快不慢。头做不到的是**另一件事**：它有质量，不可能在一
///   瞬间从"向右三百度每秒"翻成"向左三百度每秒"。
///
/// 而 V2 的实现恰恰能做到这件事——旋转角度是手指位移的**刚性函数**，手指怎么
/// 动它就怎么动，中间没有任何东西。这正是"像用手拨一个物体"的机械来源：拨动
/// 一个物体时，物体的位置确实刚性地挂在你手上；而头不是刚性地挂在意图上的。
///
/// 所以：**要改的不是速度，是加速度。**在手指与视角之间放一层惯性。
///
/// 【为什么惯性能同时满足两头（这是本方案成立的关键，不要跳过）】
///
/// 惯性滤波是**按频率**衰减的，不是按幅度衰减的。于是：
///
///   | 手指动作           | 频率成分 | 结果                                    |
///   |--------------------|---------|-----------------------------------------|
///   | 慢速稳定拖动        | 低频     | 几乎原样通过，只有一个恒定的小滞后        |
///   | 单次快速划动        | 低频     | **仍然很快**，只是有起收，不再是死起死停  |
///   | 快速左右来回晃动    | 高频     | 惯性跟不上换向，幅度被自动压掉 ✔          |
///
/// 要保留的（慢拖、快扫）和要去掉的（来回晃）恰好被同一个机制分在两侧。
/// 把问题设在"快 vs 慢"这条轴上会两难；设在"是否换向"这条轴上就不冲突。
///
/// 【实现选型：滞后加在"角度"上，不加在"角速度"上】
///
/// 有两种做法，选了前一种，这个区分很要紧：
///
///   (A) 采用 —— 手指位移累积成**目标角度**，实际角度用 SmoothDamp 去追它。
///       性质：总旋转量始终等于总手指位移。误差不累积、不漂移、不过冲。
///       手指停在哪儿，视角最终就停在哪儿——"控制感"这一条完整保留。
///
///   (B) 否决 —— 手指**速度**驱动目标角速度，再积分出角度。
///       性质：这是"甩动惯性滚动"（flick scroll）的模型。它会过冲、会漂移，
///       手指停下之后视角还要自己飞一段。那是"甩出去一个物体"，比 V2 更像
///       在拨东西，方向正好反了。
///
/// 换句话说：**惯性加在响应的过程里，不加在响应的总量上。**
///
/// 【一条重要的旁证：这个项目已经做过一次一模一样的修正】
///
/// V1 首测时**身体**转向是匀速角速度，评价是"猛地一扭头"；改成 SmoothDamp
/// 缓入缓出之后变成"很舒服"。当时记下的结论是：
///
///     "问题在曲线不在速度，把速度调慢也不对味。"
///
/// 那条结论此刻原封不动地适用于头部——只是头部这一侧从来没有被改过。
/// **身体已经有惯性了，头还没有。**本版本只是把同一个修正补到头上。
///
/// 【必须记明的代价】
///
/// 惯性就是滞后，而滞后正是会被读成"操作困难 / 跟不上手"的那个东西。
/// 所以真问题不是"要不要加"，而是"加到多少还感觉不到、加到多少开始觉得黏"。
/// 这个数**无法在桌面上定，也无法靠推理定**，必须在 iPad 上试。
/// 因此 lookSmoothTime 被做成了一个参数，且 **=0 时行为与 V2 逐帧等价**，
/// 可以直接做 A/B 对照。
///
/// ────────────────────────────────────────────────────────────────────────────
/// 【本版本改了什么】
///
///   (1) 环顾加入惯性（核心）
///       新增 lookSmoothTime、lookMaxAngularSpeed 两个参数。
///       headYaw / headPitch 拆成"目标"与"实际"两套量，实际值每帧追目标值。
///       见 UpdateLookSmoothing()。
///
///   (2) 松手吸收、点击转身、移动回正 —— 三处改为"惯性安全"的写法
///       这三处原本都直接改 headYaw。有了滞后之后直接改会把正在收尾的动作
///       拦腰截断，产生一次视觉上的顿挫。改法见 FoldHeadYawIntoBody()。
///       **行为上与 V2 等价，不是新设计**——见下面"刻意没做的事"。
///
///   (3) 调试框改为分组开关
///       本轮要判断的是转动手感，而满屏的判定读数本身就在跟画面争注意。
///       原有各行**一行未删**，只是收进 showTapDebug / showDeviceDebug 两个
///       开关里，本轮默认关闭，需要时打开即可。
///       但**危险状态不受分组开关控制**（路径采样被关、阻挡层遮罩为空、DPI
///       走了兜底值），无论开关如何都照常红字显示——这是 V1 那条教训的直接
///       延续："凡是一关就全盘失效的东西，状态必须可见"。若把这三条也收进
///       开关里，等于给自己造了第二个同类陷阱。
///
///   (4) 加入版本号常量并显示在调试框第一行
///       规范文档 2.1 的建议：在 iPad 上看一眼就知道跑的是哪一版，比看文件名
///       可靠——真机上看不见文件名。
///
/// 【本版本刻意没做的事】
///
///   - **没有改松手时"吸收进 bodyYaw、headYaw 归零"这个循环。**
///     它意味着"脖子极限"其实是**每一次拖动的极限**而不是脖子的极限（想看身后
///     转三次就行），方案A 3.2 也点名说它是"最容易让被试意识到我在操作一个装置
///     的地方"。这是个真问题，但它是**另一个**机制问题，惯性覆盖不了它。
///     本轮只动一个变量：这一轮要回答的是"惯性有没有解决拨动感"，如果同时改了
///     限位循环，报告回来的感受将无法归因。
///
///   - **没有改任何手感参数的取值**（灵敏度仍是未经测试的 12°/cm）。
///     惯性会改变"多少灵敏度算合适"这个判断，所以灵敏度要在惯性定下来之后再定，
///     不是现在。
///
///   - 没有碰"纯旋转产生光流但无视差"那条（方案A 3.2）。那说的是另一件事，
///     且**不会被本次改动解决**——原地转头本来就没有视差。不要把两件事混起来。
///
/// ════════════════════════════════════════════════════════════════════════════
/// 【V3 后半段：边走边看 —— 2026-08-10】
///
/// V3 的前半段（惯性）只处理了「转动本身」。后半段处理「转动与行走的关系」。
/// 两者合起来才是完整的 V3：环顾这件事的手感，和它在移动中的地位。
/// 前半段已在桌面上验收（研究者报告：阻尼感明显，不再像拨动物体，快划仍然够快，
/// 稳定拖动略有抵累但不违和）。
///
/// ────────────────────────────────────────────────────────────────────────────
/// 【要改的是什么】
///
/// 改动前：拖动第一帧即取消移动。于是「边走边瞥一眼」这件事不存在，每一次好奇
/// 都要付一次重新点击的代价。
///
/// 【为什么这是个问题（三条，按分量排序）】
///
///   1. **它惩罚的恰好是软迷恋本身。**
///      「注意被轻易吸引、又能轻易松开」就是软迷恋的定义。每一次随意的一瞥都
///      收费，被试会很快学会「移动时忍住别看」——而忍住别看 = 主动把注意力按在
///      路径上 = 定向注意 = 费力。这不只是削弱效应，它指向 Q2 推论 1（注意成绩
///      课后应改善而非下降）会失败的方向，而且是设计自己造成的。
///
///   2. **移动段落里，交互组在结构上接近对照组。**
///      Q2 主张交互靠「注意落点由自己不断更新」起效，预测的是过程中的轨迹分岔。
///      而一次二三十米的位移要走二十秒，这二十秒里若视角锁死，机制是停摆的。
///
///   3. **只有导航、没有别的，正是文献里反复拿到 null 的那一格。**
///      Wang et al. 2022 的自由漫游（复杂度最低、临场感最高）焦虑与抑郁都没改善；
///      Reese et al. 2021 的主动导航组压力未降。
///
/// 【这不是增加手势，是减少规则】
///
/// 手势清单改动前后一样：点击 = 走/看，拖动 = 环视。变的是拖动的**副作用**。
/// 被试原本需要学会「拖动也会让我停下来」——那才是需要学的那条规则。
/// 而且移动是发射后不管的（点一下手指就离开，行走由系统完成），所以全程单指、
/// 前后相继，没有任何同时性要求，不需要双手。
///
/// ────────────────────────────────────────────────────────────────────────────
/// 【由此必须一并回答的三个问题】
///
/// ── 问题一：那想停下来怎么办？ ──
///
/// 答：点身前的地面。不需要新动作。
///
/// 先否掉一个看似显然的方案：「点自己脚下」。它不成立，而且理由是几何的，不是
/// 语义的——眼高 1.7 m，平视时画面下缘对应的地面在 2.9 m（60° 垂直视场）到
/// 4.1 m（45°）之外。**脚下压根不在画面里。**要点到脚下得先把视角压下去，
/// 为了表达「停」先做一个「看」，两步操作还得学。
///
/// 那么「点近处地面 = 停」是不是语义混淆？不是，这里要区分两种混淆：
///   · 系统侧混淆：同一输入输出不确定，被试无法预测 —— 有害，必须避免；
///   · 意图侧多对一：不同意图产生同一输入，而系统的响应对两种意图都成立 —— 无害。
/// 点近处属于后者：系统永远只做一件事（走到该点前方保持距离处、停下、朝向它），
/// 完全确定、完全可预测。
///
/// 更准确的描述（由研究者给出）：**「走」的成分被压到可忽略，只剩「停」。**
/// 这与方案A 3.1「触碰是点击在最近端的形态」是同一个动作，只是这次落在移动通道上。
/// 实际残余：点裸地约再走 1.9 m，点植物（保持距离 2.5 m）约再走 0.4 m——
/// 而植被密集的溪谷里，画面下缘多半是植物。
///
/// 附带一条：加了边走边看之后，「我只是想看看」这个意图被拖动通道吸走了，而且
/// 免费。于是还愿意点近处的人基本就是想留在那儿的人。**边走边看不是给点击通道
/// 又塞了一个语义，是从点击通道里拿走了一个语义。**
///
/// ── 问题二：环视完之后，谁把视角转回行进方向？ ──
///
/// 这里有一个真实的两难：
///   · 让被试自己转回去 → 需要精确瞄准，违背交互原则，且会斜着走完全程；
///   · 松手即自动转回 → 他刚在侧面发现的东西还没来得及点，就被转走了。
///
/// 解法是**取消「回正是一个事件」这个前提**：
///
///     回正不是事件，是倾向。
///
/// 移动中、且屏幕上没有手指时，视角持续地、缓慢地漂回行进方向。没有触发点、
/// 没有超时常数、没有「回正完成」这个状态。
///
/// 两个矛盾之所以对撞，是因为都被塞进了「松手」这一个时刻；摊到时间上，它们落在
/// 不同的地方，不再相遇。而且真正着急的那个情形根本不走这条路——**一旦点击，
/// 转身会接管一切**（身体转向新目标、头归零、移动改道），漂移不参与。所以漂移
/// 只服务于「看完了，没什么，继续赶路」，那个情形没人在等，慢是免费的。
///
/// 想边走边一直盯着某处看：按住不放。这不是新手势，只是「漂移不跟你抢方向」的
/// 自然结果。
///
/// ── 问题三：边走边看时该走多慢？ ──
///
/// 按**视角与行进方向的夹角**连续减速，不按「手指在不在屏幕上」。
/// 理由：现实中放慢脚步不是因为手在忙，是因为没看着要去的地方。
/// 连续函数意味着不产生离散事件，且与上面两件事自动咬合（视角漂回来时速度自己
/// 恢复；按住不放时一直慢，经过那个东西的过程被拉长）。
///
/// ────────────────────────────────────────────────────────────────────────────
/// 【一个会静默失效的坑，已在实现中处理】
///
/// 「漂回行进方向」需要一个地方记住行进方向是哪边，那个地方是 bodyYaw。
/// 但松手吸收会把 bodyYaw 改写成「你刚才侧头看的方向」并把 headYaw 清零——
/// 于是回正逻辑一看 headYaw 已经是 0，认为无事可做，**被试会一直斜着走下去，
/// 而代码看上去完全正常**。
///
/// 处理：**松手吸收只在站定时发生，移动中不吸收。**详见 HandleTapInput 释放分支。
/// 附带收益：移动中头只能在 ±maxYawAngle 内偏，这恰好是对的（走路时脖子能扭
/// 七十度，想看更多得停下来转身），而在此之前那个极限每次松手都被重置、形同虚设。
/// maxYawAngle 由此从死参数变成了值得上机调的参数。
///
/// ────────────────────────────────────────────────────────────────────────────
/// 【本次刻意没做的事】
///
///   - **松手吸收循环本身没有改**（只是加了「站定时才做」这个条件）。
///     它让脖子极限变成「每次拖动的极限」这个问题仍然存在于站定状态下。
///     上一轮已判定：反复重抓的成因是手的舒适划动幅度（三五厘米，远小于屏宽），
///     不是限位机制，改限位解决不了。方案A 3.2「限位改阻尼跟转」判为**不采用**：
///     它诊断对了现象，归因错了。
///
///   - **灵敏度、maxYawAngle 的取值没有动。**这些必须上 iPad——桌面上鼠标没有
///     行程约束，那个约束是手的、不是设备的，所以在桌面上不是「没测」而是
///     **结构性地测不了**。
///
///   - 晕动不再作为约束。研究者实测：iPad 与 16" MacBook 上无论如何旋转行走都
///     不产生晕动，只有 27" 大屏会。这推翻了方案B 第八节先前的风险判断。
///
