                //
                // 「想走 / 实走」这一对是本轮第二要紧的数：理想终点是
                // 「命中点往回退 keepDistance」，但路径采样会把它削短。
                // 如果实测中到位距离经常大于 viewingDistance，多半就是这里削的，
